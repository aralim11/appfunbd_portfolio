                                    <h2 class="item-title">
                                        Robotic process automation for PG&E
                                    </h2>
                                    <p>The project aimed to automate the data retrieval process from PG&amp;E, a utility company, by developing a bot using Robomotion. The bot performs a series of tasks including logging in to the PG&amp;E website, downloading PDF files containing essential data, extracting relevant information, storing it in a database, and uploading the PDF files to both Google Drive and Digital Ocean Space. Additionally, it sends notifications to Discord at the start and resumption of the bot, and also in case of any errors occurring during the process.</p>
                                    <br>
                                    <h5>Tasks Completed:</h5>
                                    <ul>
                                        <li><strong>Init Config:</strong>
                                            <p>Configured initial settings to ensure smooth operation of the bot.</p>
                                        </li>
                                        <li><strong>Connect to Database:</strong>
                                            <p>Established a connection to the database for storing extracted data.</p>
                                        </li>
                                        <li><strong>Excel Operations:</strong>
                                            <p>Implemented functionality to access Excel files containing necessary data.</p>
                                        </li>
                                        <li><strong>Login to Website &amp; Get Accounts:</strong>
                                            <p>Automated login to the PG&amp;E website and retrieval of account information.</p>
                                        </li>
                                        <li><strong>Download &amp; Read PDF:</strong>
                                            <p>Enabled the bot to download PDF files associated with each account and read their contents.</p>
                                        </li>
                                        <li><strong>Perform OCR using Tesseract OCR:</strong>
                                            <p>Utilized Tesseract OCR for Optical Character Recognition on PDFs, extracting text data.</p>
                                        </li>
                                        <li><strong>Get Values From PDF &amp; Prepare Data:</strong>
                                            <p>Extracted relevant information from PDF files and formatted it for database storage.</p>
                                        </li>
                                        <li><strong>Insert to Database:</strong>
                                            <p>Inserted the prepared data into the database for future reference and analysis.</p>
                                        </li>
                                        <li><strong>Upload PDFs to Google Drive and Digital Ocean Space:</strong>
                                            <p>Automated the process of uploading PDF files to both Google Drive and Digital Ocean Space for backup and accessibility.</p>
                                        </li>
                                        <li><strong>Sending Notification to Discord:</strong>
                                            <p>Implemented functionality to send notifications to Discord at the start and resumption of the bot, and also in case of any errors occurring during the process.</p>
                                        </li>
                                    </ul>

